class PredictionResponse(BaseModel):
    prediction: int = Field(..., description="0 = Not Readmitted, 1 = Readmitted <30 days")
    risk_score: float = Field(..., description="Probability of readmission (0.0 to 1.0)")
    risk_category: str = Field(..., description="Risk category: Low / Medium / High")
    threshold: float = Field(..., description="Classification threshold used")
    model_version: str = Field(..., description="Name/version of the model used")
    disclaimer: str = Field(..., description="Academic disclaimer — not for clinical use")


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool
    model_version: str
    model_loaded_at: Optional[str]
    timestamp: str
    disclaimer: str


