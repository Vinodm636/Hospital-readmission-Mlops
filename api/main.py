@app.get("/health", response_model=HealthResponse, summary="Health Check")
async def health():
    """
    Service health check.

    Returns the current status of the API including whether the model
    is loaded and ready to serve predictions.
    """
    return HealthResponse(
        status="ok" if _model is not None else "degraded_no_model",
        model_loaded=_model is not None,
        model_version=_model_version,
        model_loaded_at=_model_loaded_at,
        timestamp=datetime.now().isoformat(),
        disclaimer=DISCLAIMER,
    )


@app.post("/predict", response_model=PredictionResponse, summary="Predict Readmission Risk")
async def predict(input_data: PredictionInput):
    """
    Predict 30-day hospital readmission risk for a patient encounter.

    **Input:** Patient encounter features (demographics, diagnoses, medications, etc.)

    **Output:**
    - `prediction`: 1 = High risk of readmission (<30 days), 0 = Not predicted
    - `risk_score`: Predicted probability (0.0–1.0)
    - `risk_category`: Low / Medium / High
    - `disclaimer`: Academic use only — not for clinical decision-making

    **⚕️ IMPORTANT:** This is an academic prototype. DO NOT use for patient care.
    """
    if _model is None or _preprocessor is None:
        raise HTTPException(
            status_code=503,
            detail=(
                "Model not loaded. Run ml/train.py first, then restart the API. "
                "See README for instructions."
            ),
        )

    try:
        from ml.predict import predict_readmission

        result = predict_readmission(
            feature_dict=input_data.dict(),
            model=_model,
            preprocessor=_preprocessor,
        )

        return PredictionResponse(**result)

    except Exception as exc:
        logger.error("Prediction error: %s", exc)
        raise HTTPException(
            status_code=500,
            detail=f"Prediction failed: {str(exc)}",
        )


@app.get("/model/info", summary="Model Information")
async def model_info():
    """Return information about the currently loaded model."""
    if _model is None:
        return {
            "status": "not_loaded",
            "message": "Run ml/train.py first, then restart the API.",
            "disclaimer": DISCLAIMER,
        }

    info = {
        "model_type": type(_model).__name__,
        "model_version": _model_version,
        "loaded_at": _model_loaded_at,
        "disclaimer": DISCLAIMER,
        "target": "readmission_binary (1 = readmitted <30 days)",
        "dataset": "UCI Diabetes 130-US Hospitals",
        "academic_use_only": True,
    }

    # Add parameters if available
    try:
        info["parameters"] = {k: str(v) for k, v in _model.get_params().items()}
    except Exception:
        pass

    return info
